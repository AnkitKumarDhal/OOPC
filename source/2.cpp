#include <iostream>
using namespace std;

int main()
{
    int a, b;

    cout << "Enter the two numbers: ";
    cin >> a >> b;

    cout << endl << "Sum of the two numbers is: " << a + b << endl;
    cout << "Difference of the two numbers is: " << a - b << endl;
    cout << "Product of the two numbers is: " << a * b << endl;
    cout << "Division of the two numbers is: " << a / b << endl;
    cout << "Modulus of the two numbers is: " << a % b << endl;

    return 0;
}
